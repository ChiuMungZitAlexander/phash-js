// Fixed cos(k*pi/64) samples for the 32-point hash DCT. Embedding these values
// avoids differences between JavaScript engines' transcendental functions.
const QUARTER_COSINES = [
  1, 0.9987954562051724, 0.9951847266721969, 0.989176509964781, 0.9807852804032304,
  0.970031253194544, 0.9569403357322088, 0.9415440651830208, 0.9238795325112867, 0.9039892931234433,
  0.881921264348355, 0.8577286100002721, 0.8314696123025452, 0.8032075314806449, 0.773010453362737,
  0.7409511253549591, 0.7071067811865476, 0.6715589548470183, 0.6343932841636455,
  0.5956993044924335, 0.5555702330196023, 0.5141027441932217, 0.4713967368259978,
  0.4275550934302822, 0.38268343236508984, 0.33688985339222005, 0.29028467725446233,
  0.24298017990326398, 0.19509032201612833, 0.14673047445536175, 0.09801714032956077,
  0.049067674327418126, 0,
];

export function hashCosine(sample: number, frequency: number): number {
  const phase = ((2 * sample + 1) * frequency) % 128;
  if (phase <= 32) return QUARTER_COSINES[phase];
  if (phase <= 64) return -QUARTER_COSINES[64 - phase];
  if (phase <= 96) return -QUARTER_COSINES[phase - 64];
  return QUARTER_COSINES[128 - phase];
}
